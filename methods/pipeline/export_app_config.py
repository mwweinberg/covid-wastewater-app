"""
Export everything the app's runtime module needs into ONE config file:
handoff/threshold_config.json (copied into the app repo as
pipeline/threshold_config.json). Run after every refit; the app never fits.

Collects, per city, the frozen series parameters and the fitted conversion:
  Berlin: data/berlin_wastewater_params.json, data/fit_params.json
  NYC/DC: data/us_wastewater_params.json, data/us_fit_params.json,
          data/nyc_cdc_snapshot.csv, data/dc_wval_snapshot.csv
plus the shared readout rules (threshold formula, band factors, wording,
trend rule, projection rules, CDC category cut-offs), so the app has no
hard-coded numbers (checklist C4).

Usage: python3 pipeline/export_app_config.py
"""

import json
from datetime import date

import pandas as pd

from common import PROJECT_ROOT

DATA = PROJECT_ROOT / "data"
OUT = PROJECT_ROOT / "handoff" / "threshold_config.json"


def snapshot_dict(df, key_cols):
    """CSV snapshot -> nested dict for JSON, values rounded to 6 decimals."""
    if len(key_cols) == 1:
        return {str(r.week_end.date()): round(float(r.log10_weekly), 6) for r in df.itertuples()}
    out = {}
    for r in df.itertuples():
        out.setdefault(r.plant, {})[str(r.week_end.date())] = round(float(r.lw), 6)
    return out


def main():
    bw = json.loads((DATA / "berlin_wastewater_params.json").read_text(encoding="utf-8"))
    bf = json.loads((DATA / "fit_params.json").read_text())
    uw = json.loads((DATA / "us_wastewater_params.json").read_text())
    uf = json.loads((DATA / "us_fit_params.json").read_text())
    pp = json.loads((DATA / "prevalence_params.json").read_text())
    nyc_snap = pd.read_csv(DATA / "nyc_cdc_snapshot.csv", parse_dates=["week_end"])
    dc_snap = pd.read_csv(DATA / "dc_wval_snapshot.csv", parse_dates=["week_end"]).dropna()

    def conversion(f):
        return {"a": f["a"], "b": f["b"], "w_ref": f.get("w_ref", f.get("w_ref_log10")), "lag_weeks": f["lag_weeks"]}

    cfg = {
        "description": "Frozen parameters and readout rules for the wastewater threshold readout. Generated by "
                       "pipeline/export_app_config.py in the methods project; do not edit by hand. "
                       "prevalence = 10 ** (a + b * (w - w_ref)), w = log10 trailing 2-week mean of the city series.",
        "generated": str(date.today()),
        "threshold": {
            # threshold = cases/100k/day x days_infectious x unreported multiplier (Wachter, 2022);
            # computed, never hard-coded, so days_infectious cancels out of the category (C4).
            "cases_per_100k_per_day": 10, "days_infectious": pp["days_infectious"], "unreported_multiplier": 4,
            "band_factors": [0.5, 1 / 1.4, 1.4, 2.0],
            "labels": ["Well below the threshold", "Just below the threshold", "Right around the threshold",
                       "Just above the threshold", "Well above the threshold"],
            "short_labels": ["Well below", "Just below", "Right around", "Just above", "Well above"],
            "alert_band_index": 2,       # alert level condition: at or above "Right around"
        },
        "one_in_n": {"significant_figures": 2, "min_n": 20, "max_n": 10000},
        "trend": {"window_weeks": 3, "factor": 1.25, "labels": {"rising": "rising", "falling": "falling",
                                                                "steady": "steady"}},
        "cities": {
            "berlin": {
                "week": "iso_monday_to_sunday",
                "comparable_since": bw["calibration_period_start"],
                "conversion": conversion(bf),
                "series": {"plants": bw["plants"], "plant_weights": bw["plant_weights_einwohner"],
                           "plant_offsets_log10": bw["plant_offsets_log10"],
                           "floor_values_raw_copies_per_l": bw["floor_values_raw_copies_per_l"],
                           "value_column": "viruslast_normalisiert"},
                "projection": {"method": "damped_trend", "phi": 0.7, "max_weeks": 3},
                "confidence_label": None,
                "unit": "gene copies / L",
            },
            "nyc": {
                "week": "us_sunday_to_saturday",
                "comparable_since": uw["nyc"]["comparable_since"],
                "conversion": conversion(uf["nyc"]),
                "series": {"methods_in_preference_order": uw["nyc"]["methods"],
                           "plant_weights": uw["nyc"]["plant_weights_population"],
                           "plant_offsets_log10": uw["nyc"]["plant_offsets_log10"],
                           "cdc_site_map": uw["nyc"]["cdc_site_map"],
                           "cdc_translation_slopes": uw["nyc"]["cdc_translation_slopes"],
                           "cdc_intercepts_at_freeze": uw["nyc"]["cdc_intercepts_at_freeze"],
                           "intercept_weeks": 12, "method_drift_max_log10": 0.17609,
                           "cdc_snapshot_log10_wval": snapshot_dict(nyc_snap, ["plant", "week_end"])},
                "projection": {"method": "last_value", "delayed_after_weeks": 3},
                "confidence_label": uf["nyc"]["confidence"],
                "unit": "gene copies / L",
            },
            "dc": {
                "week": "us_sunday_to_saturday",
                "comparable_since": uw["dc"]["comparable_since"],
                "conversion": conversion(uf["dc"]),
                "series": {"site": uw["dc"]["site"], "sources": uw["dc"]["sources"],
                           "cdc_snapshot_log10_wval": snapshot_dict(dc_snap, ["week_end"])},
                "projection": {"method": "last_value", "delayed_after_weeks": 3},
                "confidence_label": uf["dc"]["confidence"],
                "unit": "CDC wastewater viral activity level",
            },
        },
        "cdc_restatement": {"drop_top_share": 0.02, "tolerance": 0.01, "max_resid_sd_log10": 0.05},
        # CDC WVAL category cut-offs (upper bounds of Very Low / Low / Moderate / High), August 2026,
        # from cdc.gov/wastewater/about/wval.html and checked against site_wval_category in the data.
        # CDC re-evaluates them every August: check then.
        "cdc_category_cutoffs_2026_08": {"covid": [2.6, 4.9, 7.9, 11.6], "fluA": [2.4, 5.5, 10.2, 15.6],
                                         "rsv": [1.7, 3.4, 5.4, 8.1]},
    }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(cfg, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
